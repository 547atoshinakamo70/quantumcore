#!/usr/bin/env node

import { execSync } from 'child_process';
import { writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

/**
 * Generate build metadata and write to web/src/build-info.ts
 * This script extracts commit information, timestamp, and CI environment data
 */

function execGitCommand(command, fallback = 'unknown') {
  try {
    return execSync(command, { encoding: 'utf8', cwd: join(__dirname, '..') }).trim();
  } catch {
    return fallback;
  }
}

function getBuildMetadata() {
  const now = new Date();
  
  // Try to get git information, fallback gracefully
  const commitSha = execGitCommand('git rev-parse HEAD');
  const shortSha = execGitCommand('git rev-parse --short HEAD');
  const branch = execGitCommand('git rev-parse --abbrev-ref HEAD', 'main');
  const tag = execGitCommand('git describe --tags --exact-match 2>/dev/null || echo ""');
  const commitDate = execGitCommand('git log -1 --format=%ci');
  
  // CI environment variables
  const runId = process.env.GITHUB_RUN_ID || process.env.APPVEYOR_BUILD_ID || null;
  const runNumber = process.env.GITHUB_RUN_NUMBER || process.env.APPVEYOR_BUILD_NUMBER || null;
  const actor = process.env.GITHUB_ACTOR || process.env.APPVEYOR_ACCOUNT_NAME || null;
  const repository = process.env.GITHUB_REPOSITORY || process.env.APPVEYOR_REPO_NAME || null;
  
  const buildInfo = {
    commit: {
      sha: commitSha,
      shortSha,
      date: commitDate || now.toISOString(),
      branch,
      tag: tag || null
    },
    build: {
      timestamp: now.toISOString(),
      date: now.toLocaleDateString(),
      time: now.toLocaleTimeString(),
      runId,
      runNumber,
      actor,
      repository
    },
    version: '1.0.0' // Could be read from package.json if needed
  };
  
  return buildInfo;
}

function generateTypeScriptFile(buildInfo) {
  const content = `// This file is auto-generated by scripts/write-build-metadata.mjs
// Do not edit manually - it will be overwritten on each build

export interface BuildInfo {
  commit: {
    sha: string;
    shortSha: string;
    date: string;
    branch: string;
    tag: string | null;
  };
  build: {
    timestamp: string;
    date: string;
    time: string;
    runId: string | null;
    runNumber: string | null;
    actor: string | null;
    repository: string | null;
  };
  version: string;
}

export const BUILD_INFO: BuildInfo = ${JSON.stringify(buildInfo, null, 2)};

export default BUILD_INFO;
`;
  
  return content;
}

function main() {
  try {
    console.log('🔧 Generating build metadata...');
    
    const buildInfo = getBuildMetadata();
    const tsContent = generateTypeScriptFile(buildInfo);
    const outputPath = join(__dirname, '..', 'web', 'src', 'build-info.ts');
    
    writeFileSync(outputPath, tsContent, 'utf8');
    
    console.log('✅ Build metadata generated successfully');
    console.log(`📝 File: ${outputPath}`);
    console.log(`🔗 Commit: ${buildInfo.commit.shortSha} (${buildInfo.commit.branch})`);
    console.log(`⏰ Built: ${buildInfo.build.date} ${buildInfo.build.time}`);
    
  } catch (error) {
    console.error('❌ Failed to generate build metadata:', error.message);
    process.exit(1);
  }
}

main();